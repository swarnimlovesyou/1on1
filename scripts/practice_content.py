def enrich(lessons, problems):
    problem_ids = {p['id'] for p in problems}
    for lesson in lessons:
        alg = lesson['experiment']['algorithm']
        if alg not in PRACTICE or lesson.get('referenceJourney'):
            continue
        spec = PRACTICE[alg]
        scene = dict(lesson['experiment'])
        challenges = []
        cp = lesson.get('checkpoint')
        if cp:
            # the original checkpoint keeps its id, so earlier attempts and their evidence still count
            challenges.append(dict(id=f"challenge-{lesson['id']}-checkpoint", kind='prediction', title='Check your intuition',
                                   prompt=cp['question'], options=cp['options'], hint=lesson.get('invariant', '')))
        for kind, key, title in [('prediction', 'predict', 'Predict the next change'), ('pattern', 'pattern', 'Spot the pattern')]:
            prompt, options, answer, explanation, hint = spec[key]
            assert 0 <= answer < len(options), (alg, kind)
            challenges.append(dict(id=f'challenge-{alg}-{kind}', kind=kind, title=title, prompt=prompt, options=options,
                                   answer=answer, explanation=explanation, hint=hint))
        prompt, step, fields, hint = spec['dry']
        challenges.append(dict(id=f'challenge-{alg}-dry-run', kind='dry-run', title='Dry-run the state', prompt=prompt, scene=scene,
                               traceStep=step, fields=[dict(key=k, label=label) for k, label in fields],
                               explanation='Your entries agree with the actual Java trace for this input.', hint=hint))
        lesson['challenges'] = challenges
        linked = ['problem-' + slug for slug in spec['linked']]
        missing = [p for p in linked if p not in problem_ids]
        assert not missing, (alg, missing)
        lesson['linkedProblems'] = linked
